/** 한자 → 한글 (음절표를 거꾸로 읽는다) */
const READING = (() => {
  const map = new Map<string, string>()
  Object.entries(HANJA_SYLLABLES).forEach(([sound, chars]) => {
    chars.forEach((c) => { if (!map.has(c)) map.set(c, sound) })
  })
  /* 낱말 사전에만 있는 한자도 읽을 수 있게 채운다 */
  Object.entries(HANJA_WORDS).forEach(([word, picks]) => {
    picks.forEach((p) => {
      if (p.hanja.length !== word.length) return
      for (let i = 0; i < word.length; i++) if (!map.has(p.hanja[i])) map.set(p.hanja[i], word[i])
    })
  })
  return map
})()

const isHangul = (s: string) => /^[가-힣]+$/.test(s)

/** 이 말에 맞는 한자들 — 낱말 사전이 먼저, 없으면 한 자짜리는 음절표에서 */
export function hanjaCandidates(word: string): HanjaPick[] {
  const w = word.trim()
  if (!w || !isHangul(w)) return []
  const exact = HANJA_WORDS[w]
  if (exact) return exact
  if (w.length === 1) return (HANJA_SYLLABLES[w] || []).map((h) => ({ hanja: h, mean: '' }))
  /* 사전에 없는 여러 음절 말은 첫 음절부터 하나씩 고르게 안내한다 */
  return []
}

export interface HanjaLookup {
  /** 한자로 바꿀 앞부분 */
  stem: string
  /** 그대로 남길 뒷부분 — 「보고한다」 의 「한다」, 「회의를」 의 「를」 */
  tail: string
  picks: HanjaPick[]
}

/**
 * 우리말은 뒤에 붙는 것이 많다 — 「보고한다」·「회의를」 처럼.
 * 사전에 없으면 앞에서부터 잘라 보며 아는 말을 찾고, 뒤에 붙은 것은 한글로 그대로 남긴다.
 */
export function lookupHanja(text: string): HanjaLookup {
  const w = text.trim()
  if (!w || !isHangul(w)) return { stem: w, tail: '', picks: [] }

  const direct = hanjaCandidates(w)
  if (direct.length) return { stem: w, tail: '', picks: direct }

  /* 긴 앞부분부터 — 「주차장」 이 「주차」 보다 먼저 걸리게 */
  for (let len = w.length - 1; len >= 1; len--) {
    const stem = w.slice(0, len)
    const picks = HANJA_WORDS[stem]
    if (picks) return { stem, tail: w.slice(len), picks }
  }
  return { stem: w, tail: '', picks: [] }
}

/** 한 음절씩 고를 수 있게 쪼갠다 (사전에 없는 낱말용) */
export function syllableChoices(word: string): { sound: string; picks: string[] }[] {
  return [...word.trim()].map((sound) => ({ sound, picks: HANJA_SYLLABLES[sound] || [] }))
}

/** 고른 한자를 어떤 모양으로 넣을지 */
export function hanjaText(hangul: string, hanja: string, mode: HanjaMode): string {
  if (mode === 'both') return `${hangul}(${hanja})`
  if (mode === 'hanjaFirst') return `${hanja}(${hangul})`
  return hanja
}

/** 한자를 한글 소리로 되돌린다 — 읽지 못하는 자는 그대로 둔다 */
export function hanjaToHangul(text: string): string {
  return [...text].map((c) => READING.get(c) || c).join('')
}

/** 골라 둔 글에 한자가 섞여 있나 (되돌리기 단추를 보일지 정한다) */
export function looksHanja(text: string): boolean {
  return /[㐀-鿿]/.test(text)
}
